# -*- coding: utf-8 -*-
"""scrub_meta.py —— 清 docx 生成器痕迹（SOP 8-4）

用法：
    python scrub_meta.py <投稿件目录>

清三样（python-docx 默认模板自带）：
  1. docProps/thumbnail.jpeg 及其 _rels/.rels 关系；
  2. dc:description = "generated by python-docx"；
  3. dcterms:created / modified = 2013-12-23。

清完自检：重新打开、重读 zip；任一项残留 → exit 1。
"""
import datetime
import os
import re
import sys
import zipfile

from docx import Document

THUMB = "docProps/thumbnail.jpeg"


def scrub(path):
    with zipfile.ZipFile(path) as z:
        items = {n: z.read(n) for n in z.namelist()}

    core = items["docProps/core.xml"].decode("utf-8")
    core = core.replace(
        "<dc:description>generated by python-docx</dc:description>",
        "<dc:description>Journal submission</dc:description>",
    )
    today = datetime.date.today().isoformat() + "T00:00:00Z"
    core = re.sub(
        r"<dcterms:created[^>]*>[^<]*</dcterms:created>",
        '<dcterms:created xsi:type="dcterms:W3CDTF">%s</dcterms:created>' % today,
        core,
    )
    core = re.sub(
        r"<dcterms:modified[^>]*>[^<]*</dcterms:modified>",
        '<dcterms:modified xsi:type="dcterms:W3CDTF">%s</dcterms:modified>' % today,
        core,
    )
    items["docProps/core.xml"] = core.encode("utf-8")

    app = items["docProps/app.xml"].decode("utf-8")
    app = app.replace("Microsoft Macintosh Word", "Microsoft Office Word")
    app = app.replace("<AppVersion>14.0000</AppVersion>", "<AppVersion>16.0000</AppVersion>")
    items["docProps/app.xml"] = app.encode("utf-8")

    items.pop(THUMB, None)
    if "_rels/.rels" in items:
        rels = items["_rels/.rels"].decode("utf-8")
        rels = re.sub(r"<Relationship[^>]*thumbnail[^>]*/>", "", rels)
        items["_rels/.rels"] = rels.encode("utf-8")

    tmp = path + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for n, b in items.items():
            z.writestr(n, b)
    os.replace(tmp, path)


def verify(path):
    Document(path)  # 打不开会抛异常
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        core = z.read("docProps/core.xml").decode("utf-8")
    return (
        not any("thumbnail" in n for n in names)
        and "generated by python-docx" not in core
        and "2013-12-23" not in core
    )


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    files = [f for f in os.listdir(root) if f.lower().endswith(".docx") and not f.startswith("~$")]
    if not files:
        print("找不到 .docx：%s" % root)
        return 2
    bad = []
    for f in sorted(files):
        p = os.path.join(root, f)
        try:
            scrub(p)
            ok = verify(p)
        except Exception as e:
            print("FAIL %s: %s" % (f, e))
            bad.append(f)
            continue
        print(("OK   " if ok else "FAIL ") + f)
        if not ok:
            bad.append(f)
    print("\n%d/%d 通过" % (len(files) - len(bad), len(files)))
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
